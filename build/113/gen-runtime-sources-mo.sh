#!/usr/bin/env bash
# OpenModelica-Full-Wasm — **RuntimeSources.mo 生成器**（需求 A 前置；2026-10-13）
# Copyright (C) 2026 ArchivalEra · SPDX-License-Identifier: AGPL-3.0-or-later
#
# ── 为什么需要它（这是本批最深的一个坑，逐条有出处）──────────────────────────
#  · `OM_OMC_WASM=ON` 跳过**整个** `OMCompiler/SimulationRuntime`
#    （`OMCompiler/CMakeLists.txt:224-226` 的 `if(NOT OM_OMC_WASM)`）；
#  · 而 `SimulationRuntime/c/CMakeLists.txt:191-192` 正是 `RuntimeSources.mo` 的
#    **唯一生成点**（`include(cmake/source_code_fmu_config.cmake)` + `configure_file(...)`）；
#  · mmtorust 的源表把 `SimulationRuntime/c/RuntimeSources.mo` 列进去
#    （`Compiler/.cmake/meta_modelica_source_list.cmake:527`）；
#  · 该文件被 gitignore（`OMCompiler/.gitignore:140`）⇒ clean checkout **没有它**；
#  · 官方 CI 专门 `stash name: 'runtime-sources-mo'` / `unstash`（`.CI/common.groovy:554-556,652`），
#    注释原文："Generated by the SimulationRuntime cmake (skipped in the wasm build);
#    the web codegen reads it from the source tree, so hand it over."
#  · 缺失时 mmtorust **不报错**（`mmtorust/src/main.rs:492-520` 记 failures 但不 exit(1)）
#    ⇒ **静默半缺**（`Compiler/CMakeLists.txt:47-52` 有官方描述）。
#
# ⇒ 本脚本做官方 CI 做的同一件事：**用上游自己的生成器**产这个文件（同样的
#    `source_code_fmu_config.cmake` + 同样的 `RuntimeSources.mo.cmake` 模板 + 同样的
#    `configure_file` 替换）。不手抄、不伪造 —— 换上游版本时模板跟着变。
#    ⚠️ 我们**不跑完整 native configure**（那需要 Fortran/minizip 等一堆本机没有的
#    native 依赖；实测撞了两次墙）。只取这一个文件的生成路径。
#
# 用法：
#   bash build/113/gen-runtime-sources-mo.sh generate [--upstream <树>]
#   bash build/113/gen-runtime-sources-mo.sh status   [--upstream <树>]
#   bash build/113/gen-runtime-sources-mo.sh --dry-run
#   bash build/113/gen-runtime-sources-mo.sh --selftest
set -uo pipefail
REPO="$(cd "$(dirname "$0")/../.." && pwd)"
UPSTREAM="${UPSTREAM:-/mnt/hdd/openmodelica-wasm-build/build/upstream/openmodelica}"
WORK="${WORK:-/mnt/hdd/openmodelica-wasm-build/build/runtime-sources-mo}"

# ── 纯逻辑（自证走这里）──────────────────────────────────────────────────────
# 生成物判据：非空 + 含包名 + 含两个**必被替换**的清单占位（证明 configure_file 真跑过，
# 不是把模板原样拷了一份 —— 后者是本仓反复警惕的"看起来有文件"假成功）。
content_ok() {  # $1=文件路径 → ok / 说明
  if [ ! -s "${1:-}" ]; then echo "生成物不存在或为空（$1）"; return; fi
  grep -q 'encapsulated package RuntimeSources' "$1" || { echo "不是 RuntimeSources 包（模板没替换？）"; return; }
  grep -q '@SOURCE_FMU' "$1" && { echo "模板占位**未被替换**（configure_file 没跑）"; return; }
  grep -qE 'constant list<String> simrt_c_sources=\{' "$1" || { echo "缺 simrt_c_sources 清单"; return; }
  grep -qE 'constant list<String> simrt_c_runtime_sources=\{' "$1" || { echo "缺 simrt_c_runtime_sources 清单"; return; }
  echo ok
}
selftest() {
  bad=0; n=0
  t() { n=$((n+1)); if [ "$2" = "$3" ]; then echo "PASS | $1"; else echo "fail | $1（期望 '$3' 实得 '$2'）"; bad=$((bad+1)); fi; }
  D="$(mktemp -d)"
  # ① 正常不报：真生成物形状
  cat > "$D/good.mo" <<'EOF'
encapsulated package RuntimeSources
  constant list<String> simrt_c_sources={"a.c","b.c"};
  constant list<String> simrt_c_runtime_sources={"a.c"};
end RuntimeSources;
EOF
  t "正常：真生成物 ⇒ ok"                    "$(content_ok "$D/good.mo")" "ok"
  # ② 该报的必须报
  cp "$D/good.mo" "$D/unsub.mo"; printf '\n// @SOURCE_FMU_COMMON_FILES@\n' >> "$D/unsub.mo"
  t "★ 模板占位未替换（configure_file 没跑）⇒ 必须报" "$(content_ok "$D/unsub.mo" | grep -c '未被替换')" "1"
  printf 'encapsulated package SomethingElse\nend SomethingElse;\n' > "$D/wrong.mo"
  t "★ 不是 RuntimeSources 包 ⇒ 必须报"      "$(content_ok "$D/wrong.mo" | grep -c '不是 RuntimeSources')" "1"
  printf 'encapsulated package RuntimeSources\n  constant String x="1";\nend RuntimeSources;\n' > "$D/nolists.mo"
  t "★ 缺清单（只有包名）⇒ 必须报"           "$(content_ok "$D/nolists.mo" | grep -c '缺 simrt_c_sources')" "1"
  # ③ 空输入必须报
  t "★ 空文件 ⇒ 必须报（零值守卫）"           "$(content_ok "$D/empty.mo" 2>/dev/null | grep -c '不存在或为空')" "1"
  t "★ 空路径 ⇒ 必须报"                      "$(content_ok '' | grep -c '不存在或为空')" "1"
  rm -rf "$D"
  echo "=== gen-runtime-sources-mo 自证：$((n-bad)) PASS / $bad fail ==="
  [ "$bad" -eq 0 ]
}
case "${1:-}" in --selftest) selftest; exit $? ;; esac
[ $# -gt 0 ] && shift || true
while [ $# -gt 0 ]; do case "$1" in --upstream) UPSTREAM="$2"; shift 2 ;; *) echo "未知参数 $1" >&2; exit 2 ;; esac; done

SRC="$UPSTREAM/OMCompiler/SimulationRuntime/c"
TP="$UPSTREAM/OMCompiler/3rdParty"
OUTMO="$SRC/RuntimeSources.mo"

case "${1:-generate}" in
  --dry-run)
    echo "[dry-run] 生成 $OUTMO"
    echo "[dry-run]   生成器 = $SRC/cmake/source_code_fmu_config.cmake + $SRC/RuntimeSources.mo.cmake"
    echo "[dry-run]   （影子命令消掉 install/target 装配；只取变量替换）"
    exit 0
    ;;
  status)
    V="$(content_ok "$OUTMO")"
    if [ "$V" = ok ]; then echo "ok（$OUTMO，$(stat -c%s "$OUTMO") 字节）"; else echo "BAD: $V"; exit 1; fi
    exit 0
    ;;
  generate) ;;
  *) echo "用法: gen-runtime-sources-mo.sh generate|status|--dry-run|--selftest" >&2; exit 2 ;;
esac

[ -f "$SRC/RuntimeSources.mo.cmake" ] || { echo "FATAL: 找不到模板 $SRC/RuntimeSources.mo.cmake" >&2; exit 3; }
[ -d "$TP" ] || { echo "FATAL: 找不到 3rdParty $TP" >&2; exit 3; }
if [ -s "$OUTMO" ] && [ "$(content_ok "$OUTMO")" = ok ]; then
  echo "   已生成且形状正确 ⇒ 跳过（$(stat -c%s "$OUTMO") 字节）"
  exit 0
fi

mkdir -p "$WORK"
cat > "$WORK/CMakeLists.txt" <<'CMAKE'
cmake_minimum_required(VERSION 3.20)
project(gen_runtime_sources C)
# ── 影子命令：source_code_fmu_config.cmake 里除了"算变量 + 定路径"之外还有
#    install() 与 target 装配（那是给真构建用的）。我们只取变量 ⇒ 把那些命令
#    定义成空函数（include() 在调用者作用域里跑，函数定义生效）。
function(install)
endfunction()
function(add_library)
endfunction()
function(target_sources)
endfunction()
function(target_link_libraries)
endfunction()
function(target_compile_definitions)
endfunction()
function(target_include_directories)
endfunction()
set(OMCompiler_3rdParty_SOURCE_DIR "@TP@" CACHE PATH "")
set(CMAKE_INSTALL_DATAROOTDIR "share")
set(OM_USE_SYSTEM_CMINPACK OFF)
include("@SRC@/cmake/source_code_fmu_config.cmake")
configure_file("@SRC@/RuntimeSources.mo.cmake" "@OUTMO@" @ONLY)
message(STATUS "RuntimeSources.mo -> @OUTMO@")
CMAKE
sed -i "s|@TP@|$TP|; s|@SRC@|$SRC|; s|@OUTMO@|$OUTMO|" "$WORK/CMakeLists.txt"

cmake -S "$WORK" -B "$WORK/build" > "$WORK/configure.log" 2>&1 || {
  echo "FATAL: 生成 RuntimeSources.mo 的 configure 失败（tail $WORK/configure.log）" >&2
  tail -20 "$WORK/configure.log" >&2; exit 1; }

V="$(content_ok "$OUTMO")"
if [ "$V" != ok ]; then
  echo "FATAL: 生成物判据不过：$V" >&2; exit 1
fi
echo "   ✅ $OUTMO（$(stat -c%s "$OUTMO") 字节，sha256=$(sha256sum "$OUTMO" | cut -c1-16)…）"
